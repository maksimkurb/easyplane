#!/usr/bin/env bash
# Copy the upstream EasyTier protobuf definitions for a pinned ref into
# proto/easytier/ and regenerate the TypeScript bindings.
#
# Usage: scripts/sync-protos.sh <tag|commit>
#
# Source checkout resolution (first match wins):
#   1. $EASYTIER_REF_REPO            (e.g. /home/maksimkurb/Dev/EasyTier)
#   2. ./vendor/EasyTier             (unused by default)
#   3. /home/maksimkurb/Dev/EasyTier
#   4. clone $EASYTIER_GIT_URL into a temporary directory
#
# Only easytier-proto/proto/*.proto is imported from upstream; nothing else is
# vendored. See docs/PROTOCOL.md for the accompanying notes.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROTO_DIR="$ROOT_DIR/proto/easytier"
UPSTREAM_PROTO_SUBPATH="easytier-proto/proto"
GIT_URL="${EASYTIER_GIT_URL:-https://github.com/EasyTier/EasyTier.git}"

if [[ $# -ne 1 ]]; then
  echo "usage: $0 <tag|commit>" >&2
  exit 2
fi
REF="$1"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

resolve_repo() {
  local candidates=()
  [[ -n "${EASYTIER_REF_REPO:-}" ]] && candidates+=("$EASYTIER_REF_REPO")
  candidates+=("$ROOT_DIR/vendor/EasyTier" "/home/maksimkurb/Dev/EasyTier")
  for candidate in "${candidates[@]}"; do
    if [[ -d "$candidate/.git" ]] && git -C "$candidate" cat-file -e "$REF^{commit}" 2>/dev/null; then
      echo "$candidate"
      return 0
    fi
  done
  return 1
}

if REPO="$(resolve_repo)"; then
  echo "using upstream checkout: $REPO"
else
  REPO="$TMP_DIR/EasyTier"
  echo "cloning $GIT_URL (shallow) into $REPO"
  git init --quiet "$REPO"
  git -C "$REPO" remote add origin "$GIT_URL"
  git -C "$REPO" fetch --quiet --depth 1 origin "$REF" || git -C "$REPO" fetch --quiet origin
  git -C "$REPO" checkout --quiet "$REF"
fi

COMMIT="$(git -C "$REPO" rev-parse "$REF^{commit}")"
COMMIT_DATE="$(git -C "$REPO" show -s --format=%cI "$COMMIT")"
COMMIT_SUBJECT="$(git -C "$REPO" show -s --format=%s "$COMMIT")"

echo "pinned ref $REF -> $COMMIT ($COMMIT_DATE)"

EXTRACT_DIR="$TMP_DIR/extract"
mkdir -p "$EXTRACT_DIR"
git -C "$REPO" archive "$COMMIT" "$UPSTREAM_PROTO_SUBPATH" | tar -x -C "$EXTRACT_DIR"

SRC="$EXTRACT_DIR/$UPSTREAM_PROTO_SUBPATH"
if ! compgen -G "$SRC/*.proto" >/dev/null; then
  echo "error: no .proto files found at $UPSTREAM_PROTO_SUBPATH in $COMMIT" >&2
  exit 1
fi

rm -rf "$PROTO_DIR"
mkdir -p "$PROTO_DIR"
cp "$SRC"/*.proto "$PROTO_DIR"/

cat >"$PROTO_DIR/UPSTREAM_REF" <<EOF
# Generated by scripts/sync-protos.sh -- do not edit.
ref=$REF
commit=$COMMIT
commit_date=$COMMIT_DATE
commit_subject=$COMMIT_SUBJECT
source=$UPSTREAM_PROTO_SUBPATH
EOF

echo "copied $(ls -1 "$PROTO_DIR"/*.proto | wc -l) proto files to proto/easytier"
"$ROOT_DIR/scripts/generate-protos.sh"
