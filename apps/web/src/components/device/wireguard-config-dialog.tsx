import { useTranslation } from "react-i18next"
import { QRCodeSVG } from "qrcode.react"
import { DownloadIcon, KeyRoundIcon } from "lucide-react"

import { getDownloadWireguardClientConfigUrl } from "@/api/generated/easyplane"
import type { ListWireguardClients200Item } from "@/api/generated/model"
import { CopyButton } from "@/components/copy-button"
import { Button } from "@/components/ui/button"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"
import { Skeleton } from "@/components/ui/skeleton"
import { WireguardBadge } from "@/components/device/wireguard-badge"

/**
 * The ready-made WireGuard config is fetched on demand from the hub: it is
 * generated by the portal (which owns the key derivation) and contains a
 * private key, so it is never cached and never shown anywhere else.
 */
export function WireguardConfigDialog({
  client,
  config,
  loading,
  error,
  open,
  onOpenChange,
  onRetry,
}: {
  client: ListWireguardClients200Item | null
  config: string | null
  loading: boolean
  error: Error | null
  open: boolean
  onOpenChange: (open: boolean) => void
  onRetry?: () => void
}) {
  const { t } = useTranslation()
  const downloadUrl =
    client && config
      ? getDownloadWireguardClientConfigUrl(client.id)
      : undefined

  return (
    <Dialog onOpenChange={onOpenChange} open={open}>
      <DialogContent size="sm">
        <DialogHeader>
          <DialogTitle>{t("wireguard.configTitle")}</DialogTitle>
          <DialogDescription>
            {t("wireguard.configDescription")}
          </DialogDescription>
        </DialogHeader>

        {client ? (
          <div className="flex flex-wrap items-center gap-2 text-sm">
            <span className="font-semibold">{client.name}</span>
            <WireguardBadge />
            <span className="font-mono text-xs text-fg-3">
              {client.virtualIpv4}
            </span>
          </div>
        ) : null}

        {loading ? (
          <div className="flex flex-col items-center gap-3 py-6">
            <Skeleton className="size-56 rounded-xl" />
            <span className="text-[13px] text-fg-3">
              {t("wireguard.loadingConfig")}
            </span>
          </div>
        ) : config ? (
          <div className="flex flex-col items-center gap-3">
            <div className="rounded-xl bg-white p-3 ring-1 ring-line">
              <QRCodeSVG
                aria-label={t("wireguard.qrLabel")}
                className="size-52 max-w-full sm:size-56"
                level="M"
                role="img"
                value={config}
              />
            </div>
            <p className="flex items-start gap-1.5 text-xs text-fg-3">
              <KeyRoundIcon aria-hidden="true" className="mt-0.5 size-3.5 flex-none" />
              <span className="text-pretty">{t("wireguard.configHint")}</span>
            </p>
            <Button
              className="h-11 w-full sm:h-10"
              onClick={async () => {
                if (downloadUrl) window.location.assign(downloadUrl)
              }}
              type="button"
              variant="outline"
            >
              <DownloadIcon className="size-4" />
              {t("wireguard.download")}
            </Button>
          </div>
        ) : (
          <div className="flex flex-col items-start gap-2 rounded-lg bg-surface-2 px-3 py-3 text-[13px]">
            <p className="font-medium">{t("wireguard.configUnavailable")}</p>
            <p className="break-words text-fg-2">
              {error?.message ?? t("wireguard.configOffline")}
            </p>
            {onRetry ? (
              <Button onClick={onRetry} size="sm" type="button" variant="outline">
                {t("common.retry")}
              </Button>
            ) : null}
          </div>
        )}

        <DialogFooter>
          {config ? (
            <CopyButton
              className="h-11 sm:h-10"
              label={t("common.copy")}
              value={config}
            />
          ) : null}
          <Button
            className="h-11 sm:h-10"
            onClick={() => onOpenChange(false)}
            type="button"
            variant="outline"
          >
            {t("common.close")}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  )
}
