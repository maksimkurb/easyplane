import { useTranslation } from "react-i18next"
import { QRCodeSVG } from "qrcode.react"
import { DownloadIcon, KeyRoundIcon } from "lucide-react"

import {
  getDownloadDeviceWireguardPortalConfigUrl,
  useGetDeviceWireguardPortalConfig,
} from "@/api/generated/easyplane"
import { CopyButton } from "@/components/copy-button"
import { Button } from "@/components/ui/button"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"
import { Skeleton } from "@/components/ui/skeleton"

/**
 * Shared WireGuard config of a legacy (< 2.7.0) portal. 2.6.x serves exactly
 * one ready-made config for its whole `client_cidr` pool, generated by the
 * device; the panel only fetches it on demand (it contains a private key) and
 * never stores or logs it.
 */
export function WireguardSharedConfigDialog({
  deviceId,
  open,
  onOpenChange,
}: {
  deviceId: string
  open: boolean
  onOpenChange: (open: boolean) => void
}) {
  const { t } = useTranslation()
  const query = useGetDeviceWireguardPortalConfig(deviceId, {
    query: { enabled: open, retry: false, gcTime: 0, staleTime: 0 },
  })
  const result = query.data?.data ?? null
  const config = result?.config ?? null

  return (
    <Dialog onOpenChange={onOpenChange} open={open}>
      <DialogContent size="sm">
        <DialogHeader>
          <DialogTitle>{t("wireguard.sharedConfigTitle")}</DialogTitle>
          <DialogDescription>
            {t("wireguard.sharedConfigDescription")}
          </DialogDescription>
        </DialogHeader>

        {query.isLoading ? (
          <div className="flex flex-col items-center gap-3 py-6">
            <Skeleton className="size-56 rounded-xl" />
            <span className="text-[13px] text-fg-3">
              {t("wireguard.loadingConfig")}
            </span>
          </div>
        ) : config ? (
          <div className="flex flex-col items-center gap-3">
            <div className="rounded-xl bg-white p-3 ring-1 ring-line">
              <QRCodeSVG
                aria-label={t("wireguard.qrLabel")}
                className="size-52 max-w-full sm:size-56"
                level="M"
                role="img"
                value={config}
              />
            </div>
            <p className="text-[13px] text-fg-2">
              {result?.clientCidr
                ? t("wireguard.sharedConfigPool", { cidr: result.clientCidr })
                : null}
            </p>
            <p className="text-[13px] text-fg-3">
              {t("wireguard.connectedClients", {
                count: result?.connectedClients.length ?? 0,
              })}
            </p>
            <p className="flex items-start gap-1.5 text-xs text-fg-3">
              <KeyRoundIcon aria-hidden="true" className="mt-0.5 size-3.5 flex-none" />
              <span className="text-pretty">{t("wireguard.configHint")}</span>
            </p>
            <Button
              className="h-11 w-full sm:h-10"
              onClick={() => {
                window.location.assign(
                  getDownloadDeviceWireguardPortalConfigUrl(deviceId)
                )
              }}
              type="button"
              variant="outline"
            >
              <DownloadIcon className="size-4" />
              {t("wireguard.download")}
            </Button>
          </div>
        ) : (
          <div className="flex flex-col items-start gap-2 rounded-lg bg-surface-2 px-3 py-3 text-[13px]">
            <p className="font-medium">{t("wireguard.sharedConfigUnavailable")}</p>
            <p className="break-words text-fg-2">
              {(query.error as Error | null)?.message ??
                t("wireguard.sharedConfigNotRunning")}
            </p>
            <Button
              onClick={() => void query.refetch()}
              size="sm"
              type="button"
              variant="outline"
            >
              {t("common.retry")}
            </Button>
          </div>
        )}

        <DialogFooter>
          {config ? (
            <CopyButton
              className="h-11 sm:h-10"
              label={t("common.copy")}
              value={config}
            />
          ) : null}
          <Button onClick={() => onOpenChange(false)} type="button" variant="ghost">
            {t("common.close")}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  )
}
