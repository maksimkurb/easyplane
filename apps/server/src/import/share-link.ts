import { deflateSync, inflateSync } from "node:zlib";

import type { manage } from "@easyplane/proto";

import {
  NETWORK_CONFIG_FIELD_NAMES,
  NETWORK_CONFIG_FIELD_NUMBERS,
  fromPbjson,
  toPbjson,
} from "./pbjson.js";

/**
 * EasyTier config share links.
 *
 * `easytier-contrib/easytier-ohrs/src/config/services/share_link_service.rs`
 * (pinned commit 81487c363a5677…):
 *
 *   URL    = https://easytier.cn/comp_cfg?cfg=<payload>[&name=<display>][&only_start=true]
 *   payload = base64url_no_pad( zlib( JSON ) )
 *   JSON    = pbjson NetworkConfig with every *top level* key replaced by its
 *             protobuf field number ("6" instead of "network_name")
 *
 * Upstream only accepts its own host; EasyPlane also accepts links generated by
 * other control planes/hosts as long as the path is `/comp_cfg` (documented).
 */

export const SHARE_LINK_HOST = "easytier.cn";
export const SHARE_LINK_PATH = "/comp_cfg";
export const SHARE_LINK_MAX_BYTES = 1024 * 1024;

export interface ShareLinkPayload {
  config: manage.NetworkConfig;
  /** `name` query parameter, used as the suggested network name. */
  displayName: string | undefined;
  onlyStart: boolean;
  warnings: string[];
}

function fromBase64Url(value: string): Buffer {
  const normalized = value.replace(/-/g, "+").replace(/_/g, "/");
  const padded = normalized.padEnd(Math.ceil(normalized.length / 4) * 4, "=");
  return Buffer.from(padded, "base64");
}

export function networkConfigToShareLink(
  config: manage.NetworkConfig,
  options: { displayName?: string; onlyStart?: boolean; host?: string } = {},
): string {
  const pbjson = toPbjson(config);
  const mapped: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(pbjson)) {
    const number = NETWORK_CONFIG_FIELD_NUMBERS[key];
    if (number === undefined) {
      // A future field EasyPlane does not know; keep the name so a newer GUI
      // can still read it.
      mapped[key] = value;
      continue;
    }
    mapped[String(number)] = value;
  }
  const compressed = deflateSync(Buffer.from(JSON.stringify(mapped), "utf8"), {
    level: 9,
  });
  const payload = compressed.toString("base64url");
  const url = new URL(
    `https://${options.host ?? SHARE_LINK_HOST}${SHARE_LINK_PATH}`,
  );
  url.searchParams.set("cfg", payload);
  if (options.displayName) url.searchParams.set("name", options.displayName);
  if (options.onlyStart) url.searchParams.set("only_start", "true");
  return url.toString();
}

export function decodeShareLink(input: string): ShareLinkPayload {
  const trimmed = input.trim();
  if (trimmed === "") throw new Error("share link is empty");

  let payload: string;
  let displayName: string | undefined;
  let onlyStart = false;
  let host: string | undefined;
  let path: string | undefined;

  if (/^https?:\/\//i.test(trimmed)) {
    let url: URL;
    try {
      url = new URL(trimmed);
    } catch {
      throw new Error("invalid share link URL");
    }
    host = url.host;
    path = url.pathname;
    const cfg = url.searchParams.get("cfg");
    if (!cfg) throw new Error("share link has no cfg parameter");
    payload = cfg;
    displayName = url.searchParams.get("name") ?? undefined;
    onlyStart = url.searchParams.get("only_start") === "true";
  } else {
    payload = trimmed;
  }

  if (path !== undefined && path !== SHARE_LINK_PATH) {
    throw new Error(
      `share link path must be ${SHARE_LINK_PATH} (got ${path})`,
    );
  }
  if (payload.length > SHARE_LINK_MAX_BYTES) {
    throw new Error("share link payload is too large");
  }

  let inflated: Buffer;
  try {
    inflated = inflateSync(fromBase64Url(payload), {
      maxOutputLength: SHARE_LINK_MAX_BYTES,
    });
  } catch (error) {
    throw new Error(
      `share link payload is not zlib+base64url: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(inflated.toString("utf8"));
  } catch (error) {
    throw new Error(
      `share link payload is not JSON: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new Error("share link payload must be a JSON object");
  }

  const warnings: string[] = [];
  const remapped: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(parsed as Record<string, unknown>)) {
    if (/^\d+$/.test(key)) {
      const name = NETWORK_CONFIG_FIELD_NAMES[key];
      if (!name) {
        warnings.push(`unknown NetworkConfig field number ${key} was ignored`);
        continue;
      }
      remapped[name] = value;
    } else {
      // Some exporters keep field names; accept those too.
      remapped[key] = value;
    }
  }

  let config: manage.NetworkConfig;
  try {
    config = fromPbjson(remapped);
  } catch (error) {
    throw new Error(
      `share link config is invalid: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  }

  return {
    config,
    displayName,
    onlyStart,
    warnings,
  };
}

/** Parses a link and returns a warning list including host differences. */
export function describeShareLinkOrigin(input: string): string {
  const trimmed = input.trim();
  if (!/^https?:\/\//i.test(trimmed)) return "raw payload";
  try {
    return new URL(trimmed).host;
  } catch {
    return "invalid URL";
  }
}
