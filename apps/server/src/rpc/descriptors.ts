/**
 * Service descriptors used on the config-server control channel.
 *
 * Upstream references (pinned commit 81487c3):
 * - easytier-proto/proto/web.proto          -> WebServerService (server side, tiny)
 * - easytier-proto/proto/api_manage.proto   -> WebClientService (client side)
 * - easytier-proto/build/rpc.rs             -> method indexes start at 1
 * - easytier-web/src/client_manager/session.rs -> scoped_client(1, 1, "")
 */

export interface RpcDescriptor {
  domainName: string;
  protoName: string;
  serviceName: string;
  methodIndex: number;
}

